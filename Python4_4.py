#!/usr/bin/env python3

# Exercício 4 - imprimir de 1 a 100 com loop while
contagem = 1
while contagem < 101: #assim, ele conta até antes de 101, ou seja, até 100
    print('contagem: ', contagem)
    contagem+=1 #isso significa contagem = contagem + 1. Assim, inicia-se no 1 e soma-se 1 até a contagem limite